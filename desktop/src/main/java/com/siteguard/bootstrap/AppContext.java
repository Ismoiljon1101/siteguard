package com.siteguard.bootstrap;

import com.siteguard.adapter.simulation.FleetSimulator;
import com.siteguard.adapter.sqlite.SqliteDatabase;
import com.siteguard.adapter.sqlite.SqliteStore;
import com.siteguard.application.port.Store;
import com.siteguard.application.service.AssignmentService;
import com.siteguard.application.service.AuthService;
import com.siteguard.application.service.DemoSeedService;
import com.siteguard.application.service.GeneratedCredential;
import com.siteguard.application.service.HealthService;
import com.siteguard.application.service.IncidentService;
import com.siteguard.application.service.IngestService;
import com.siteguard.application.service.OperatorSeedService;
import com.siteguard.application.service.PasswordHasher;
import com.siteguard.application.service.SiteQueryService;
import com.siteguard.domain.Device;
import com.siteguard.domain.Site;
import java.io.PrintStream;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.time.Clock;
import java.util.List;

/**
 * Composition root. One call wires the database, migrations, first-run seeds and all services.
 * Blocking: it hashes three demo passwords on first run (about a second), so call it off the Swing thread.
 */
public final class AppContext implements AutoCloseable {
    public static final String DATABASE_FILE = "siteguard.db";
    public static final String CREDENTIALS_FILE = "demo-credentials.txt";

    private final Store store;
    private final SiteQueryService queries;
    private final IncidentService incidents;
    private final IngestService ingest;
    private final AssignmentService assignments;
    private final HealthService health;
    private final AuthService auth;
    private final SimulationRunner simulation;
    private final long demoSiteId;
    private final List<GeneratedCredential> firstRunCredentials;

    private AppContext(Store store, Clock clock, PasswordHasher hasher, List<GeneratedCredential> firstRun, long demoSiteId,
                       List<String> simulatedHelmets) {
        this.store = store;
        this.queries = new SiteQueryService(store, clock);
        this.incidents = new IncidentService(store, clock);
        this.ingest = new IngestService(store, clock);
        this.assignments = new AssignmentService(store, clock);
        this.health = new HealthService(store, clock);
        this.auth = new AuthService(store, clock, hasher);
        this.demoSiteId = demoSiteId;
        this.firstRunCredentials = firstRun;
        this.simulation = new SimulationRunner(new FleetSimulator(simulatedHelmets, Long.toHexString(clock.millis())),
                ingest, health, incidents, () -> Long.toHexString(clock.millis()));
    }

    /** Production entry: system UTC clock, PBKDF2 at the OWASP iteration count, credentials printed to System.out once. */
    public static AppContext open(Path dataDir) {
        return open(dataDir, Clock.systemUTC(), new PasswordHasher(), System.out);
    }

    public static AppContext open(Path dataDir, Clock clock, PasswordHasher hasher, PrintStream console) {
        SqliteStore store = SqliteStore.open(new SqliteDatabase(dataDir.resolve(DATABASE_FILE)));
        List<GeneratedCredential> created = new OperatorSeedService(store, clock, hasher, new SecureRandom()).seedIfEmpty();
        if (!created.isEmpty()) {
            DemoCredentialsFile.write(dataDir.resolve(CREDENTIALS_FILE), created, clock.instant());
            if (console != null) {
                console.println("SiteGuard first run. Demo operator credentials (shown once, also saved in "
                        + dataDir.resolve(CREDENTIALS_FILE) + "):");
                for (GeneratedCredential c : created) {
                    console.println("  " + c.loginId() + "  " + c.role() + "  " + c.password());
                }
            }
        }
        new DemoSeedService(store, clock).seedIfAbsent();
        Site site = store.read(r -> r.sites().findSiteByName(DemoSeedService.SITE_NAME).orElseThrow());
        List<String> simulated = store.read(r -> r.devices().list(site.siteId()).stream()
                .filter(Device::simulated).map(Device::deviceId).toList());
        return new AppContext(store, clock, hasher, created, site.siteId(), simulated);
    }

    public SiteQueryService queries() { return queries; }
    public IncidentService incidents() { return incidents; }
    public IngestService ingest() { return ingest; }
    public AssignmentService assignments() { return assignments; }
    public HealthService health() { return health; }
    public AuthService auth() { return auth; }
    /** Start, stop, reset and script the simulated helmets (SIMULATED data only). */
    public SimulationRunner simulation() { return simulation; }
    public long demoSiteId() { return demoSiteId; }

    /** Plaintext credentials generated by this call, empty after the first run. Do not log or store them. */
    public List<GeneratedCredential> firstRunCredentials() { return firstRunCredentials; }

    @Override public void close() { simulation.close(); }
}
